/** Palette data format (data/palettes.json). Own code; the data itself derives from perler-beads (see vendor/perler-beads/NOTICE.md). */

export interface PaletteColorEntry {
  /** Stable index (0-based), equals array position. */
  id: number;
  /** "#RRGGBB" uppercase. */
  hex: string;
  /** Primary color code per brand. */
  codes: Record<string, string>;
  /** Extra codes some sources list for the same color (e.g. CSV "157/70"). */
  altCodes?: Record<string, string[]>;
  /** perler-beads value, when `hex` was replaced by a MARD value fetched locally. */
  vendorHex?: string;
}

export interface PaletteTier {
  /** e.g. "t72" or "all". */
  id: string;
  size: number;
  /** true = generated by an algorithm, not an official kit list. */
  synthetic: boolean;
  method: string;
  colorIds: number[];
}

export interface KnownIssue {
  brand: string;
  code: string;
  hexes: string[];
  note: string;
}

export interface PaletteData {
  _source: Record<string, string>;
  schemaVersion: 1;
  brands: string[];
  colors: PaletteColorEntry[];
  tiers: PaletteTier[];
  knownIssues: KnownIssue[];
}

const HEX_RE = /^#[0-9A-F]{6}$/;

/** Structural + consistency checks. Returns a list of human-readable errors (empty = valid). */
export function validatePaletteData(data: PaletteData): string[] {
  const errors: string[] = [];
  const seenHex = new Map<string, PaletteColorEntry>();
  data.colors.forEach((c, i) => {
    if (c.id !== i) errors.push(`color #${i}: id ${c.id} != position`);
    if (!HEX_RE.test(c.hex)) errors.push(`color #${i}: bad hex "${c.hex}"`);
    // a fetched MARD value may coincide with another bead's screen color (H2 white = T1
    // transparent, both #FFFFFF); matching then prefers the lower id, i.e. the standard bead
    const twin = seenHex.get(c.hex);
    if (twin && !twin.vendorHex && !c.vendorHex) errors.push(`color #${i}: duplicate hex ${c.hex}`);
    if (!twin) seenHex.set(c.hex, c);
    for (const b of data.brands) {
      const code = c.codes[b];
      if (typeof code !== 'string' || code.trim() === '') errors.push(`color ${c.hex}: missing ${b} code`);
    }
    for (const b of Object.keys(c.codes)) if (!data.brands.includes(b)) errors.push(`color ${c.hex}: unknown brand ${b}`);
  });

  // per-brand code uniqueness; documented duplicates must match knownIssues exactly
  const allowed = new Set(data.knownIssues.map((k) => `${k.brand}\u0000${k.code}`));
  const found = new Set<string>();
  for (const b of data.brands) {
    const byCode = new Map<string, string[]>();
    for (const c of data.colors) {
      const code = c.codes[b];
      if (!code) continue;
      byCode.set(code, [...(byCode.get(code) ?? []), c.hex]);
    }
    byCode.forEach((hexes, code) => {
      if (hexes.length < 2) return;
      const key = `${b}\u0000${code}`;
      found.add(key);
      if (!allowed.has(key)) errors.push(`${b} code ${code} used by ${hexes.join(', ')}`);
    });
  }
  allowed.forEach((k) => {
    if (!found.has(k)) errors.push(`knownIssues entry ${k.replace('\u0000', ' ')} no longer applies`);
  });

  // tiers: valid ids, no duplicates, nested by size, "all" covers everything
  const sorted = data.tiers.slice().sort((a, b) => a.size - b.size);
  let prev: Set<number> | null = null;
  for (const t of sorted) {
    const ids = new Set(t.colorIds);
    if (ids.size !== t.colorIds.length) errors.push(`tier ${t.id}: duplicate ids`);
    if (t.colorIds.length !== t.size) errors.push(`tier ${t.id}: size ${t.size} != ${t.colorIds.length} ids`);
    for (const id of t.colorIds) if (!(id >= 0 && id < data.colors.length)) errors.push(`tier ${t.id}: bad id ${id}`);
    if (prev) for (const id of prev) if (!ids.has(id)) errors.push(`tier ${t.id}: not a superset of the smaller tier (missing ${id})`);
    prev = ids;
  }
  const all = data.tiers.find((t) => t.id === 'all');
  if (!all || all.size !== data.colors.length) errors.push('tier "all" missing or incomplete');
  return errors;
}
